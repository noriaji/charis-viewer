// <plus> research/157 (N13 slice 2; the only way since research/207 T1)
// The caps the viewer sets through LLGLState (its classes, llglstates.h and
// the LLGLEnable / LLGLDisable around the draw pools), each with a place in a
// fixed table instead of an entry of sStateMap. Any other cap stays in the map.
namespace
{
    constexpr LLGLenum FLAT_CAPS[] =
    {
        GL_BLEND, GL_CULL_FACE, GL_DEPTH_TEST, GL_STENCIL_TEST, GL_SCISSOR_TEST,
        GL_POLYGON_OFFSET_FILL, GL_POLYGON_OFFSET_LINE, GL_DEPTH_CLAMP,
        GL_MULTISAMPLE, GL_DITHER, GL_LINE_SMOOTH,
    };
    constexpr S32 NUM_FLAT_CAPS = (S32)LL_ARRAY_SIZE(FLAT_CAPS);

    S32 flat_cap(LLGLenum state)
    {
        switch (state)
        {
        case GL_BLEND:                  return 0;
        case GL_CULL_FACE:              return 1;
        case GL_DEPTH_TEST:             return 2;
        case GL_STENCIL_TEST:           return 3;
        case GL_SCISSOR_TEST:           return 4;
        case GL_POLYGON_OFFSET_FILL:    return 5;
        case GL_POLYGON_OFFSET_LINE:    return 6;
        case GL_DEPTH_CLAMP:            return 7;
        case GL_MULTISAMPLE:            return 8;
        case GL_DITHER:                 return 9;
        case GL_LINE_SMOOTH:            return 10;
        default:                        return -1;
        }
    }

    // The table, always (research/207 T1: the switch LLRHI_FLAT_STATE and
    // the map for these caps are gone). present[] stands for "has an entry"
    // (as sStateMap's operator[] makes one), for dumpStates / checkStates.
    struct FlatCaps
    {
        LLGLboolean value[NUM_FLAT_CAPS] = {};
        bool present[NUM_FLAT_CAPS] = {};
    };
    FlatCaps sCapTable;
}

//static
LLGLboolean& LLGLState::stateOf(LLGLenum state)
{
    const S32 i = flat_cap(state);
    if (i >= 0)
    {
        sCapTable.present[i] = true;
        return sCapTable.value[i];
    }
    return sStateMap[state];
}
// </plus>

// <plus> research/207 T4: the caps' copy for the world passes' write-through
//static
bool LLGLState::capCopy(LLGLenum state)
{
    const S32 i = flat_cap(state);
    if (i >= 0)
    {
        return sCapTable.value[i] == GL_TRUE;   // false until set, as the backend's
    }
    const auto found = sStateMap.find(state);
    return found != sStateMap.end() && found->second == GL_TRUE;
}

//static
void LLGLState::writeCap(LLGLenum state, bool on)
{
    LLGLboolean& current = stateOf(state);
    if ((current == GL_TRUE) == on)
    {
        return;
    }
    gGL.flush();
    set_gl_cap(state, on);
    current = on ? GL_TRUE : GL_FALSE;
}
// </plus>

//static
void LLGLState::initClass()
{
    // <plus> research/157: through stateOf (was sStateMap[...])
    stateOf(GL_DITHER) = GL_TRUE;
    // sStateMap[GL_TEXTURE_2D] = GL_TRUE;

    //make sure multisample defaults to disabled
    stateOf(GL_MULTISAMPLE) = GL_FALSE;
    // </plus>
    set_gl_cap(GL_MULTISAMPLE, false); // <plus> research/207 T4: through the one writer (was glDisable) </plus>
}

//static
void LLGLState::restoreGL()
{
    sStateMap.clear();
    // <plus> research/157: the flat table too
    for (S32 i = 0; i < NUM_FLAT_CAPS; ++i)
    {
        sCapTable.present[i] = false;
        sCapTable.value[i] = GL_FALSE;
    }
    // </plus>
    initClass();
}

//static
// Really shouldn't be needed, but seems we sometimes do.
void LLGLState::resetTextureStates()
{
    gGL.flush();
    GLint maxTextureUnits;

    glGetIntegerv(GL_MAX_TEXTURE_IMAGE_UNITS, &maxTextureUnits);
    for (S32 j = maxTextureUnits-1; j >=0; j--)
    {
        gGL.getTexUnit(j)->activate();
        j == 0 ? gGL.getTexUnit(j)->enable(LLTexUnit::TT_TEXTURE) : gGL.getTexUnit(j)->disable();
    }
}

void LLGLState::dumpStates()
{
    LL_INFOS("RenderState") << "GL States:" << LL_ENDL;
    for (std::unordered_map<LLGLenum, LLGLboolean>::iterator iter = sStateMap.begin();
         iter != sStateMap.end(); ++iter)
    {
        LL_INFOS("RenderState") << llformat(" 0x%04x : %s",(S32)iter->first,iter->second?"true":"false") << LL_ENDL;
    }
    // <plus> research/157: the flat table's entries
    for (S32 i = 0; i < NUM_FLAT_CAPS; ++i)
    {
        if (sCapTable.present[i])
        {
            LL_INFOS("RenderState") << llformat(" 0x%04x : %s", (S32)FLAT_CAPS[i], sCapTable.value[i] ? "true" : "false") << LL_ENDL;
        }
    }
    // </plus>
}

void LLGLState::checkStates(GLboolean writeAlpha)
{
    if (!gDebugGL)
    {
        return;
    }

    GLint srcRGB, dstRGB, srcAlpha, dstAlpha;
    glGetIntegerv(GL_BLEND_SRC_RGB, &srcRGB);
    glGetIntegerv(GL_BLEND_DST_RGB, &dstRGB);
    glGetIntegerv(GL_BLEND_SRC_ALPHA, &srcAlpha);
    glGetIntegerv(GL_BLEND_DST_ALPHA, &dstAlpha);
    llassert_always(srcRGB == GL_SRC_ALPHA);
    llassert_always(srcAlpha == GL_SRC_ALPHA);
    llassert_always(dstRGB == GL_ONE_MINUS_SRC_ALPHA);
    llassert_always(dstAlpha == GL_ONE_MINUS_SRC_ALPHA);

    // disable for now until usage is consistent
    //GLboolean colorMask[4];
    //glGetBooleanv(GL_COLOR_WRITEMASK, colorMask);
    //llassert_always(colorMask[0]);
    //llassert_always(colorMask[1]);
    //llassert_always(colorMask[2]);
    // llassert_always(colorMask[3] == writeAlpha);

    for (std::unordered_map<LLGLenum, LLGLboolean>::iterator iter = sStateMap.begin();
         iter != sStateMap.end(); ++iter)
    {
        LLGLenum state = iter->first;
        LLGLboolean cur_state = iter->second;
        LLGLboolean gl_state = glIsEnabled(state);
        if(cur_state != gl_state)
        {
            dumpStates();
            LL_GL_ERRS << llformat("LLGLState error. State: 0x%04x",state) << LL_ENDL;
        }
    }
    // <plus> research/157: the flat table's entries
    for (S32 i = 0; i < NUM_FLAT_CAPS; ++i)
    {
        if (sCapTable.present[i] && sCapTable.value[i] != glIsEnabled(FLAT_CAPS[i]))
        {
            dumpStates();
            LL_GL_ERRS << llformat("LLGLState error. State: 0x%04x", FLAT_CAPS[i]) << LL_ENDL;
        }
    }
    // </plus>
}

