//static
void LLGLDepthTest::readCopy(bool& test, bool& write, U32& func)
{
    test = sDepthEnabled != GL_FALSE;
    write = sWriteEnabled != GL_FALSE;
    func = sDepthFunc;
}

//static
void LLGLDepthTest::writeTest(bool test)
{
    const GLboolean value = test ? GL_TRUE : GL_FALSE;
    if (value != sDepthEnabled)
    {
        gGL.flush();
        set_gl_cap(GL_DEPTH_TEST, test);
        sDepthEnabled = value;
    }
}

//static
void LLGLDepthTest::writeMask(bool write)
{
    const GLboolean value = write ? GL_TRUE : GL_FALSE;
    if (value != sWriteEnabled)
    {
        gGL.flush();
        set_gl_depth_mask(value);
        sWriteEnabled = value;
    }
}

//static
void LLGLDepthTest::writeFunc(U32 func)
{
    if ((GLenum)func != sDepthFunc)
    {
        gGL.flush();
        set_gl_depth_func((GLenum)func);
        sDepthFunc = (GLenum)func;
    }
}
// </plus>

void LLGLDepthTest::checkState()
{
    if (gDebugGL)
    {
        GLint func = 0;
        GLboolean mask = GL_FALSE;

        glGetIntegerv(GL_DEPTH_FUNC, &func);
        glGetBooleanv(GL_DEPTH_WRITEMASK, &mask);

        if (glIsEnabled(GL_DEPTH_TEST) != sDepthEnabled ||
            sWriteEnabled != mask ||
            sDepthFunc != func)
        {
            if (gDebugSession)
            {
                gFailLog << "Unexpected depth testing state." << std::endl;
            }
            else
            {
                LL_GL_ERRS << "Unexpected depth testing state." << LL_ENDL;
            }
        }
    }
}

