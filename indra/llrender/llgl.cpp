LLGLState::LLGLState(LLGLenum state, S32 enabled) :
    mState(state), mWasEnabled(false), mIsEnabled(false)
{
    LL_PROFILE_ZONE_SCOPED_CATEGORY_PIPELINE;

    if (mState)
    {
        mWasEnabled = stateOf(state); // <plus> research/157: was sStateMap[state] </plus>
        setEnabled(enabled);
    }
}

void LLGLState::setEnabled(S32 enabled)
{
    if (!mState)
    {
        return;
    }
    // <plus> research/157: one lookup through stateOf (was sStateMap[mState] each time)
    LLGLboolean& current = stateOf(mState);
    if (enabled == CURRENT_STATE)
    {
        enabled = current == GL_TRUE ? ENABLED_STATE : DISABLED_STATE;
    }
    else if (enabled == ENABLED_STATE && current != GL_TRUE)
    {
        gGL.flush();
        set_gl_cap(mState, true);
        current = GL_TRUE;
    }
    else if (enabled == DISABLED_STATE && current != GL_FALSE)
    {
        gGL.flush();
        set_gl_cap(mState, false);
        current = GL_FALSE;
    }
    // </plus>
    mIsEnabled = enabled;
}

LLGLState::~LLGLState()
{
    LL_PROFILE_ZONE_SCOPED_CATEGORY_PIPELINE;
    if (mState)
    {
        if (gDebugGL)
        {
            if (!gDebugSession)
            {
                llassert_always(stateOf(mState) == glIsEnabled(mState)); // <plus> research/157 </plus>
            }
            else
            {
                if (stateOf(mState) != glIsEnabled(mState)) // <plus> research/157 </plus>
                {
                    ll_fail("GL enabled state does not match expected");
                }
            }
        }

        if (mIsEnabled != mWasEnabled)
        {
            gGL.flush();
            if (mWasEnabled)
            {
                set_gl_cap(mState, true);
                stateOf(mState) = GL_TRUE; // <plus> research/157 </plus>
            }
            else
            {
                set_gl_cap(mState, false);
                stateOf(mState) = GL_FALSE; // <plus> research/157 </plus>
            }
        }
    }
}

