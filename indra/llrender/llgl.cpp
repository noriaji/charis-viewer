// return false if unable (or unwilling due to old drivers) to init GL
// <plus> research/207 T3: gGLManager from the Vulkan device (LLRHI::deviceInfo),
// not GL's strings, limits and extensions; the GL entry points the viewer
// still calls are loaded (load_gl_functions) before the backend installs
// (LLRHI::onGLFunctionsLoaded)
bool LLGLManager::initGL()
{
    if (mInited)
    {
        LL_ERRS("RenderInit") << "Calling init on LLGLManager after already initialized!" << LL_ENDL;
    }

    LLRHI::DeviceInfo device;
    if (!LLRHI::deviceInfo(device))
    {
        LL_WARNS("RenderInit") << "No Vulkan device to describe the GPU" << LL_ENDL;
        return false;
    }

    load_gl_functions();

    // The vendor and renderer upper cased, to work around driver-to-driver
    // variation in capitalization (the GPU table matches them so).
    mRawVendor = device.vendor;
    mRawRenderer = device.renderer;
    mGLVendor = device.vendor;
    LLStringUtil::toUpper(mGLVendor);
    mGLRenderer = device.renderer;
    LLStringUtil::toUpper(mGLRenderer);

    mGLVersionString = device.version;
    LL_INFOS("RenderInit") << "GL: " << mGLVersionString << LL_ENDL;
    parse_gl_version(mGLVersionString, &mDriverVersionMajor, &mDriverVersionMinor, &mDriverVersionRelease, &mDriverVersionVendorString);
    mGLVersion = mDriverVersionMajor + mDriverVersionMinor * .1f;

    mGLSLVersionString = device.glsl_version;
    parse_glsl_version(mGLSLVersionString, mGLSLVersionMajor, mGLSLVersionMinor);

    // Trailing space necessary to keep "nVidia Corpor_ati_on" cards
    // from being recognized as ATI.
    // NOTE: AMD has been pretty good about not breaking this check, do not rename without good reason
    if (mGLVendor.substr(0,4) == "ATI ")
    {
        mGLVendorShort = "AMD";
        mIsAMD = true;
    }
    else if (mGLVendor.find("NVIDIA ") != std::string::npos)
    {
        mGLVendorShort = "NVIDIA";
        mIsNVIDIA = true;
    }
    else if (mGLVendor.find("INTEL") != std::string::npos)
    {
        mGLVendorShort = "INTEL";
        mIsIntel = true;
    }
    else
    {
        mGLVendorShort = "MISC";
    }

    // GL 4.6's capabilities, as the device's GL 4.6 answers had them. Debug
    // output: the GL debug callback is answered and does nothing (Vulkan's
    // validation layers report instead).
    mHasCubeMapArray = true;
    mHasDebugOutput = true;
    mHasAnisotropic = true;

    mGLMaxVertexRange = device.max_elements_vertices;
    mGLMaxIndexRange = device.max_elements_indices;
    mGLMaxTextureSize = device.max_texture_size;

    mInited = true;
    LLRHI::onGLFunctionsLoaded();

    const U32 old_vram = mVRAM;
    mVRAM = device.vram_mb;
    if (mVRAM != 0)
    {
        LL_INFOS("RenderInit") << "VRAM Detected (Vulkan device):" << mVRAM << LL_ENDL;
    }
    if (mVRAM < 256 && old_vram > 0)
    {
        // fall back to old method
        mVRAM = old_vram;
    }

    mNumTextureImageUnits = device.max_texture_units;
    mMaxColorTextureSamples = device.max_color_texture_samples;
    mMaxDepthTextureSamples = device.max_depth_texture_samples;
    mMaxIntegerSamples = device.max_integer_samples;
    mMaxSampleMaskWords = device.max_sample_mask_words;
    mMaxSamples = device.max_samples;
    mMaxVaryingVectors = device.max_varying_vectors;
    mMaxUniformBlockSize = device.max_uniform_block_size;

    // If outside the allowed range, glLineWidth fails with "invalid value".
    mAliasedLineRange.set(device.line_width_range[0], device.line_width_range[1]);

    // sanity clamp max uniform block size to 64k just in case
    // there's some implementation that reports a crazy value
    mMaxUniformBlockSize = llmin(mMaxUniformBlockSize, 65536);

    mMaxAnisotropy = device.max_anisotropy;

    initGLStates();

    return true;
}
