// From Firestorm (indra/newview/fsfloateraddtocontactset.cpp, research/333). What changed
// (plus/contactsets/ORIGIN.md): the photo screen's look (floater_plus_contact_set_add.xml); the set is the
// pulldown's value (not its words, which are "no sets" when there are none); null ids are left out; the set's
// name in the notice is made safe for a text with links; the window's own "+" asks through
// plus::contactsets::askAddSet().

#include "llviewerprecompiledheaders.h"
#include "fsfloateraddtocontactset.h"

#include "contactsets.h"
#include "plus.h"

#include "llbutton.h"
#include "llnotificationsutil.h"
#include "llsdutil.h"
#include "llslurl.h"

FSFloaterAddToContactSet::FSFloaterAddToContactSet(const LLSD& target)
:   LLFloater(target),
    mTarget(target)
{
    mContactSetChangedConnection = LGGContactSets::getInstance()->setContactSetChangeCallback(boost::bind(&FSFloaterAddToContactSet::updateSets, this, _1));
}

FSFloaterAddToContactSet::~FSFloaterAddToContactSet()
{
    if (mContactSetChangedConnection.connected())
    {
        mContactSetChangedConnection.disconnect();
    }
}

bool FSFloaterAddToContactSet::postBuild()
{
    if (mTarget.multiple())
    {
        LLStringUtil::format_map_t args;
        args["COUNT"] = llformat("%d", mTarget.count());
        childSetValue("textfield", LLSD( getString("text_add_multiple", args) ) );
    }
    else
    {
        LLStringUtil::format_map_t args;
        args["NAME"] = mTarget.agentLink();
        childSetValue("textfield", LLSD( getString("text_add_single", args)) );
    }

    mContactSetsCombo = getChild<LLComboBox>("contact_sets");
    populateContactSets();

    childSetAction("add_btn",   boost::bind(&FSFloaterAddToContactSet::onClickAdd, this));
    childSetAction("cancel_btn", boost::bind(&FSFloaterAddToContactSet::onClickCancel, this));
    childSetAction("add_set_btn", boost::bind(&FSFloaterAddToContactSet::onClickAddSet, this));

    return true;
}

void FSFloaterAddToContactSet::onClickAdd()
{
    if (mTarget.add(mContactSetsCombo->getValue().asString()))
    {
        closeFloater();
    }
}

void FSFloaterAddToContactSet::onClickCancel()
{
    closeFloater();
}

void FSFloaterAddToContactSet::onClickAddSet()
{
    plus::contactsets::askAddSet();
}

void FSFloaterAddToContactSet::updateSets(LGGContactSets::EContactSetUpdate type)
{
    if (type == LGGContactSets::UPDATED_LISTS)
    {
        populateContactSets();
    }
}

void FSFloaterAddToContactSet::populateContactSets()
{
    if (!mContactSetsCombo)
    {
        return;
    }

    const std::string selected = mContactSetsCombo->getValue().asString();
    mContactSetsCombo->clearRows();
    bool isEmptySet = true;
    for (const std::string& set_name : mTarget.setNames())
    {
        mContactSetsCombo->add(set_name, LLSD(set_name));
        isEmptySet = false;
    }
    if (isEmptySet)
    {
        mContactSetsCombo->add(getString("no_sets"), LLSD());
        mContactSetsCombo->selectFirstItem();
    }
    else if (selected.empty() || !mContactSetsCombo->selectByValue(LLSD(selected)))
    {
        mContactSetsCombo->selectFirstItem();
    }
    getChild<LLButton>("add_btn")->setEnabled(!isEmptySet);
}
